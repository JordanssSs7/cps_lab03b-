package pe.edu.tecsup.lab03.service;

public class StudentService {
// Sumar
    public static int sumar(int a, int b) {
        return a + b;
    }

// Restar
    public static int restar(int a, int b) {
        return a - b;
    }

// Multiplicar
    public static int multiplicar(int a, int b) {
        return a * b;
    }

}
